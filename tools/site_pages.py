"""Builds shared_data/site_pages.json for the website's "How well it works", "Credits and licences" and
"What's new" pages. Every number is read from a committed file (shared_data/asl_results.json, which
tools/asl_results.py builds from the Kaggle results, and reports/performance_v3.json), never typed by hand;
tests/test_site_pages.py fails if the committed JSON and those files disagree. Master v4: ASL only.

    python tools/site_pages.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "shared_data" / "site_pages.json"

# Ledger entries the shipped website uses, and how (descriptions only; licences come from the ledger).
SHIPPED = {
    "asl-islr-1st-place-tflite": "The ASL recogniser (250 ASL signs).",
    "asl-gislr-competition-data": "The data the ASL recogniser was trained on (not shipped).",
    "asl-gislr-rerun-set": "Measures the ASL recogniser on signers it never saw; its recordings play in the guided tour.",
    "mediapipe-hand-landmarker": "Finds both hands in the camera picture, on the device.",
    "mediapipe-pose-landmarker-lite": "Finds the shoulders and arms, on the device (tells the left hand from the right).",
    "mediapipe-face-landmarker": "Finds the face points the ASL model reads, on the device.",
}
SOFTWARE_LICENCES = {"react": "MIT", "react-dom": "MIT", "@mediapipe/tasks-vision": "Apache-2.0", "@litertjs/core": "Apache-2.0", "vite": "MIT"}


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def asl_section() -> dict:
    results = read_json(ROOT / "shared_data" / "asl_results.json")
    h = results["headline"]
    groups = results["paths"]["native"]["groups"] if results["status"] == "complete" else results["groups"]
    calibration = results["paths"]["native"]["calibration"] if results["status"] == "complete" else results["calibration"]
    sure = next(c for c in calibration if c["threshold"] == 0.6)
    paths = {name: {k: path[k] for k in ("title", "samples", "top1", "top5", "left_right_gap", "ece")} for name, path in results["paths"].items()}
    return {
        "source": results["source"], "status": results["status"], "dataset": results["dataset"]["name"],
        "samples": results["dataset"]["samples_evaluated"], "signer_independence": results["dataset"]["signer_independence"],
        "measured_on": results["measured_on"][:10], "runtime": results["model"]["runtime"],
        "top1": h["native_top1"], "top5": h["native_top5"], "browser_frames": h["browser_frames"], "browser_top1": h["browser_top1"],
        "left_dominant_top1": groups["dominant_left"]["top1"], "right_dominant_top1": groups["dominant_right"]["top1"],
        "one_handed": groups["one_handed"], "two_handed": groups["two_handed"],
        "accept_at": 0.6, "right_when_sure": sure["accuracy_when_covered"], "sure_share": sure["coverage"], "paths": paths,
    }


def credits_section() -> dict:
    ledger = yaml.safe_load((ROOT / "data" / "LICENSES.yaml").read_text(encoding="utf-8"))
    by_id = {e["id"]: e for e in ledger["assets"]}
    assets = []
    for asset_id, use in SHIPPED.items():
        e = by_id[asset_id]
        assets.append({"id": asset_id, "name": e["name"], "licence": e["licence"], "attribution": e.get("attribution", ""),
                       "source_url": e.get("source_url", ""), "used_for": use, "checked": str(e.get("checked_on", ""))})
    package = json.loads((ROOT / "web" / "package.json").read_text(encoding="utf-8"))
    software = [{"name": name, "version": version, "licence": SOFTWARE_LICENCES.get(name, "see the package")}
                for name, version in sorted({**package.get("dependencies", {}), **package.get("devDependencies", {})}.items())]
    return {"source": "data/LICENSES.yaml and web/package.json", "assets": assets, "software": software}


def whats_new_section() -> list:
    sections, current = [], None
    for line in (ROOT / "docs" / "WHATS_NEW.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            current = {"title": line[3:].strip(), "items": []}
            sections.append(current)
        elif line.startswith("- ") and current is not None:
            current["items"].append(line[2:].strip())
    return sections


def performance_section() -> dict:
    performance = read_json(ROOT / "reports" / "performance_v3.json")
    rows = [m for m in performance["measurements"] if m["what"].startswith("ASL model")]
    return {"source": "reports/performance_v3.json", "measurements": rows,
            "note": "Model time per sign only; the live camera is measured in master-v4 Stage 3 on named devices."}


def build() -> dict:
    return {"about": "Generated by tools/site_pages.py from committed files; do not edit by hand.",
            "asl": asl_section(), "performance": performance_section(), "credits": credits_section(), "whats_new": whats_new_section()}


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    sys.exit(0)
